const PDFDocument = require('pdfkit');

const rs = (p) => `Rs ${(p / 100).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const day = (d) => new Date(d).toISOString().slice(0, 10);

function drawTable(doc, columns, rows, startY) {
  let y = startY;
  const rowH = 18;
  const drawRow = (cells, bold) => {
    if (y > doc.page.height - 70) { doc.addPage(); y = 50; }
    let x = 50;
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(9);
    cells.forEach((text, i) => { doc.text(String(text), x + 2, y + 4, { width: columns[i].width - 4, align: columns[i].align || 'left', lineBreak: false }); x += columns[i].width; });
    doc.moveTo(50, y + rowH).lineTo(50 + columns.reduce((s, c) => s + c.width, 0), y + rowH).strokeColor('#CCCCCC').lineWidth(0.5).stroke();
    y += rowH;
  };
  drawRow(columns.map((c) => c.label), true);
  rows.forEach((r) => drawRow(r, false));
  return y;
}

/** Account statement as a PDF stream. */
function statementPdf(res, { member, account, from, to, openingPaisa, closingPaisa, entries }) {
  const doc = new PDFDocument({ size: 'A4', margin: 50, info: { Title: `Statement ${account.accountNo}` } });
  doc.pipe(res);
  doc.font('Helvetica-Bold').fontSize(18).text('Sahakari Ledger', { continued: false });
  doc.font('Helvetica').fontSize(11).fillColor('#555555').text('Account statement').fillColor('black').moveDown(0.8);
  doc.fontSize(10);
  doc.text(`Member: ${member.fullName} (${member.membershipNo})`);
  doc.text(`Account: ${account.accountNo}`);
  doc.text(`Period: ${from ? day(from) : 'start'} to ${to ? day(to) : 'today'}`);
  doc.text(`Opening balance: ${rs(openingPaisa)}      Closing balance: ${rs(closingPaisa)}`).moveDown(0.8);
  const cols = [{ label: 'Date', width: 70 }, { label: '#', width: 40 }, { label: 'Type', width: 90 },
    { label: 'Amount', width: 90, align: 'right' }, { label: 'Balance', width: 100, align: 'right' }, { label: 'Note', width: 105 }];
  drawTable(doc, cols, entries.map((e) => [day(e.createdAt), e.seq, e.type.replace('_', ' '),
    `${e.deltaPaisa < 0 ? '-' : '+'}${(Math.abs(e.deltaPaisa) / 100).toFixed(2)}`, (e.balanceAfterPaisa / 100).toFixed(2), (e.memo || '').slice(0, 20)]), doc.y);
  doc.moveDown(2).fontSize(8).fillColor('#777777').text('Every entry is part of a tamper-evident hash chain. Generated by Sahakari Ledger.');
  doc.end();
}

/** Monthly summary as a PDF stream. */
function monthlyPdf(res, report) {
  const doc = new PDFDocument({ size: 'A4', margin: 50, info: { Title: `Monthly report ${report.month}` } });
  doc.pipe(res);
  doc.font('Helvetica-Bold').fontSize(18).text('Sahakari Ledger');
  doc.font('Helvetica').fontSize(11).fillColor('#555555').text(`Monthly summary for ${report.month}`).fillColor('black').moveDown(0.8);
  const cols = [{ label: 'Item', width: 260 }, { label: 'Entries', width: 80, align: 'right' }, { label: 'Total', width: 150, align: 'right' }];
  drawTable(doc, cols, report.rows.map((r) => [r.label, r.count, rs(r.totalPaisa)]), doc.y);
  doc.end();
}

module.exports = { statementPdf, monthlyPdf, rs };
